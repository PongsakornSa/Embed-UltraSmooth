"""Train a tiny on-device fan recommendation model from ExamBarier CSV.

CSV columns: temperature_c, humidity_rh, gas_rs_r0, fan_on
The model is a 3-input logistic regression and needs only a sigmoid at inference.
No third-party packages are required.
"""
import argparse
import csv
import math
import os

FEATURES = ("temperature_c", "humidity_rh", "gas_rs_r0")
LABEL = "fan_on"
THRESHOLD = 0.40
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER_OUT = os.path.join(ROOT, "gateway", "include", "gas_fan_model.h")


def load(path):
    rows = []
    with open(path, newline="", encoding="utf-8-sig") as stream:
        for row in csv.DictReader(stream):
            try:
                x = [float(row[name]) for name in FEATURES]
                y = 1 if float(row[LABEL]) >= 0.5 else 0
            except (KeyError, TypeError, ValueError):
                continue
            if all(math.isfinite(v) for v in x):
                rows.append((x, y))
    if len(rows) < 100 or len({y for _, y in rows}) < 2:
        raise ValueError("need at least 100 valid rows and both fan_on classes")
    return rows


def stats(rows):
    n, d = len(rows), len(FEATURES)
    mean = [sum(x[j] for x, _ in rows) / n for j in range(d)]
    std = [math.sqrt(sum((x[j] - mean[j]) ** 2 for x, _ in rows) / n) or 1.0
           for j in range(d)]
    return mean, std


def train(rows, epochs=180):
    mean, std = stats(rows)
    weights = [0.0] * (len(FEATURES) + 1)  # bias, then three feature weights
    n = len(rows)
    for epoch in range(epochs):
        grad = [0.0] * len(weights)
        for values, label in rows:
            x = [(values[j] - mean[j]) / std[j] for j in range(len(FEATURES))]
            z = weights[0] + sum(weights[j + 1] * x[j] for j in range(len(x)))
            p = 1.0 / (1.0 + math.exp(-max(-30.0, min(30.0, z))))
            error = p - label
            grad[0] += error
            for j, value in enumerate(x):
                grad[j + 1] += error * value
        rate = 0.5 / (1.0 + epoch / 120.0)
        for j in range(len(weights)):
            weights[j] -= rate * grad[j] / n
    return mean, std, weights


def probability(values, model):
    mean, std, weights = model
    z = weights[0] + sum(weights[j + 1] * ((values[j] - mean[j]) / std[j])
                          for j in range(len(FEATURES)))
    return 1.0 / (1.0 + math.exp(-max(-30.0, min(30.0, z))))


def evaluate(rows, model):
    tp = fp = fn = tn = 0
    for x, y in rows:
        prediction = probability(x, model) >= THRESHOLD
        if prediction and y: tp += 1
        elif prediction: fp += 1
        elif y: fn += 1
        else: tn += 1
    total = max(1, len(rows))
    accuracy = (tp + tn) / total
    precision = tp / max(1, tp + fp)
    recall = tp / max(1, tp + fn)
    balanced = 0.5 * (recall + tn / max(1, tn + fp))
    return accuracy, precision, recall, balanced, tp, fp, fn, tn


def c_array(values):
    return ", ".join(f"{v:.8f}f" for v in values)


def export(model, count):
    mean, std, weights = model
    with open(HEADER_OUT, "w", encoding="utf-8", newline="\n") as stream:
        stream.write("// Generated by ai/train_gas_fan_model.py; do not edit by hand.\n")
        stream.write(f"// Trained on {count} supplied ExamBarier rows.\n#pragma once\n")
        stream.write("#define GAS_FAN_MODEL_READY 1\n")
        stream.write(f"#define GAS_FAN_THRESHOLD {THRESHOLD:.2f}f\n")
        stream.write(f"static const float GAS_FAN_MEAN[3] = {{{c_array(mean)}}};\n")
        stream.write(f"static const float GAS_FAN_STD[3] = {{{c_array(std)}}};\n")
        stream.write(f"static const float GAS_FAN_WEIGHTS[4] = {{{c_array(weights)}}};\n")
    print(f"wrote {HEADER_OUT}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", help="ExamBarier combined CSV")
    args = parser.parse_args()
    rows = load(args.csv)
    split = int(len(rows) * 0.8)
    validation_model = train(rows[:split])
    metrics = evaluate(rows[split:], validation_model)
    print(f"rows={len(rows)} train={split} holdout={len(rows)-split} threshold={THRESHOLD:.2f}")
    print("holdout accuracy={:.3f} precision={:.3f} recall={:.3f} balanced_accuracy={:.3f} TP={} FP={} FN={} TN={}".format(*metrics))
    export(train(rows), len(rows))


if __name__ == "__main__":
    main()
